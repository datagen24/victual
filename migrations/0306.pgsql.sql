		ALTER TABLE consumption_events ADD CONSTRAINT consumption_events_removed_reason_known CHECK (source_removed_reason IS NULL
			OR source_removed_reason IN ('entered_in_error', 'history_cleared', 'medication_archived', 'access_revoked', 'unknown'));
