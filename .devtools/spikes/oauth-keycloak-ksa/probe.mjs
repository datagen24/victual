// Kubernetes service-account tokens as Keycloak client credentials (ADR-0057 question 6). Needs
// `./run.sh up`. Opens its own `kubectl port-forward` to Keycloak on localhost:8190, configures the
// realm through the admin API, then runs the S cases and writes results.json and a Markdown table.
// "pass" and "FAIL" compare against the proposal in question 6; "obs" records behaviour it does not
// decide yet. About 1 minute.
import { execFileSync, spawn } from "node:child_process";
import { randomBytes } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const CTX = process.env.KCSA_CONTEXT ?? "kind-kind-cluster";
const NS = "kcsa-spike";
const KC = "http://localhost:8190";
const REALM = "victual";
const ISSUER = `${KC}/realms/${REALM}`;
const TOKEN = `${ISSUER}/protocol/openid-connect/token`;
const ASSERTION = "urn:ietf:params:oauth:client-assertion-type:jwt-bearer";
const TX = "urn:ietf:params:oauth:grant-type:token-exchange";
const results = [];
// Generated by run.sh into .secrets.env (gitignored); the test user's password is new every run.
const ADMIN_PASSWORD = /^ADMIN_PASS=(.*)$/m.exec(readFileSync(new URL("./.secrets.env", import.meta.url), "utf8"))[1];
const ALICE_PASSWORD = randomBytes(16).toString("hex");

/** Runs kubectl in the spike's context; returns trimmed stdout. */
const kubectl = (...args) => execFileSync("kubectl", ["--context", CTX, ...args], { encoding: "utf8" }).trim();
/** A TokenRequest token for a service account (`kubectl create token`). */
const saToken = (sa, { ns = NS, audience = ISSUER, duration = "10m" } = {}) => kubectl("-n", ns, "create", "token", sa, `--audience=${audience}`, `--duration=${duration}`);
/** Decodes a JWT payload without verifying it. */
const claims = (t) => JSON.parse(Buffer.from(t.split(".")[1], "base64url"));
/** Waits the given number of milliseconds. */
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
/** Appends one case result: pass, FAIL, or obs. */
function record(id, clause, expected, observed, ok) {
  results.push({ id, clause, expected, observed: String(observed), verdict: ok === "obs" ? "obs" : ok ? "pass" : "FAIL" });
  console.error(`${new Date().toISOString().slice(11, 19)} ${id} ${results.at(-1).verdict}`);
}
/** POSTs a form to the token endpoint; returns `{ status, ...json }`. */
async function token(form) {
  const r = await fetch(TOKEN, { method: "POST", body: new URLSearchParams(form) });
  return { status: r.status, ...(await r.json().catch(() => ({}))) };
}
/** Short label of a token response. */
const st = (r) => (r.access_token ? `200 token (azp ${claims(r.access_token).azp})` : `${r.status} ${r.error ?? ""}${r.error_description ? ` (${String(r.error_description).slice(0, 90)})` : ""}`);
/** A client-credentials grant authenticated by a service-account token, optionally naming a client. */
const cc = (assertion, extra = {}) => token({ grant_type: "client_credentials", client_assertion_type: ASSERTION, client_assertion: assertion, ...extra });

// --- port-forward to Keycloak for the life of this process
const pf = spawn("kubectl", ["--context", CTX, "-n", NS, "port-forward", "svc/keycloak", "8190:8080"], { stdio: "ignore" });
process.on("exit", () => pf.kill());
for (let i = 0; i < 60; i++) { try { if ((await fetch(`${KC}/realms/master`)).ok) break; } catch { /* not yet */ } await sleep(1000); }

// --- admin API (bootstrap admin from the master realm)
let adminTok;
/** Calls Keycloak's admin API for the spike realm (or `/admin/realms` itself with realm ""); returns the parsed body. */
async function admin(method, path, body, { realm = REALM, raw = false } = {}) {
  if (!adminTok) adminTok = (await (await fetch(`${KC}/realms/master/protocol/openid-connect/token`, { method: "POST",
    body: new URLSearchParams({ grant_type: "password", client_id: "admin-cli", username: "admin", password: ADMIN_PASSWORD }) })).json()).access_token;
  const r = await fetch(`${KC}/admin/realms${realm ? `/${realm}` : ""}${path}`, { method, headers: { Authorization: `Bearer ${adminTok}`, "Content-Type": "application/json" }, body: body && JSON.stringify(body) });
  if (raw) return r;
  if (!r.ok) throw new Error(`${method} ${path} -> ${r.status} ${(await r.text()).slice(0, 300)}`);
  const t = await r.text();
  return t ? JSON.parse(t) : null;
}

// --- realm: the cluster as a Kubernetes identity provider; one federated-jwt client per workload
const saIssuer = claims(saToken("victual-label-worker")).iss;
await admin("DELETE", `/${REALM}`, undefined, { realm: "", raw: true });
await admin("POST", "", { realm: REALM, enabled: true, accessTokenLifespan: 300 }, { realm: "" });
await admin("POST", "/identity-provider/instances", { alias: "kubernetes", providerId: "kubernetes", enabled: true, config: { issuer: saIssuer } });
/** Creates a client and returns its id. */
async function client(clientId, body) {
  await admin("POST", "/clients", { clientId, enabled: true, protocol: "openid-connect", publicClient: false, standardFlowEnabled: false, ...body });
  return (await admin("GET", `/clients?clientId=${encodeURIComponent(clientId)}`))[0].id;
}
/** A client authenticated by the given service account's token. */
const federated = (clientId, sa, extra = {}) => client(clientId, { serviceAccountsEnabled: true, clientAuthenticatorType: "federated-jwt",
  ...extra, attributes: { "jwt.credential.issuer": "kubernetes", "jwt.credential.sub": `system:serviceaccount:${NS}:${sa}`, ...(extra.attributes ?? {}) } });
const ids = {
  worker: await federated("victual-label-worker", "victual-label-worker"),
  renderer: await federated("victual-label-renderer", "victual-label-renderer"),
};
// The sidecar exchanges user tokens (ADR-0055 decision 7): /api audience scope, exchange switch on.
await admin("POST", "/client-scopes", { name: "api-audience", protocol: "openid-connect", attributes: { "include.in.token.scope": "false" },
  protocolMappers: [{ name: "api", protocol: "openid-connect", protocolMapper: "oidc-audience-mapper", config: { "included.client.audience": "victual-api", "access.token.claim": "true" } }] });
await admin("POST", "/client-scopes", { name: "mcp-audience", protocol: "openid-connect", attributes: { "include.in.token.scope": "false" },
  protocolMappers: [{ name: "sidecar", protocol: "openid-connect", protocolMapper: "oidc-audience-mapper", config: { "included.client.audience": "victual-mcp", "access.token.claim": "true" } }] });
await client("victual-api", { serviceAccountsEnabled: false });
ids.mcp = await federated("victual-mcp", "victual-mcp", { serviceAccountsEnabled: false, attributes: { "standard.token.exchange.enabled": "true" } });
const scopes = await admin("GET", "/client-scopes");
await admin("PUT", `/clients/${ids.mcp}/default-client-scopes/${scopes.find((s) => s.name === "api-audience").id}`);
// A spike-only user and a direct-grant client stand in for an MCP client's user token.
const userClient = await client("spike-user-client", { publicClient: true, directAccessGrantsEnabled: true });
await admin("PUT", `/clients/${userClient}/default-client-scopes/${scopes.find((s) => s.name === "mcp-audience").id}`);
await admin("POST", "/users", { username: "alice", email: "alice@example.invalid", emailVerified: true, enabled: true, firstName: "a", lastName: "b",
  credentials: [{ type: "password", value: ALICE_PASSWORD, temporary: false }] });

// S0: the two features are on as shipped (no KC_FEATURES in k8s.yaml).
{
  const feats = (await (await fetch(`${KC}/admin/serverinfo`, { headers: { Authorization: `Bearer ${adminTok}` } })).json()).features
    .filter((f) => ["KUBERNETES_SERVICE_ACCOUNTS", "CLIENT_AUTH_FEDERATED"].includes(f.name));
  record("S0", "ADR-0055 d2: nothing required relies on Preview", "both features DEFAULT and enabled with no feature flag set",
    feats.map((f) => `${f.name} ${f.type} ${f.enabled ? "enabled" : "off"}`).join("; ") + `; service-account issuer ${saIssuer}`, feats.length === 2 && feats.every((f) => f.type === "DEFAULT" && f.enabled));
}
// S1: the worker pod's projected token.
const podToken = kubectl("-n", NS, "exec", "worker", "--", "cat", "/var/run/secrets/tokens/kctoken");
{
  const r = await cc(podToken);
  const c = r.access_token ? claims(r.access_token) : {};
  const pc = claims(podToken);
  record("S1", "ADR-0057 q6: an in-cluster workload authenticates with no stored secret", "the pod's projected token (audience = realm issuer) gets a client-credentials token for victual-label-worker",
    `${st(r)}; access token sub ${c.sub ? "service-account user" : "-"}, ${c.exp - c.iat} s; pod token sub ${pc.sub}, pod-bound: ${!!pc["kubernetes.io"]?.pod}, ${pc.exp - pc.iat} s`, c.azp === "victual-label-worker");
}
// S2: a TokenRequest token (kubectl create token) for the renderer's account.
const rendererToken = saToken("victual-label-renderer");
{
  const r = await cc(rendererToken);
  record("S2", "ADR-0057 q6", "a TokenRequest token gets a token for victual-label-renderer", st(r), r.access_token && claims(r.access_token).azp === "victual-label-renderer");
}
// S3 to S5: the wrong account, the wrong namespace, the wrong audience.
{
  const r1 = await cc(saToken("intruder"));
  const r2 = await cc(rendererToken, { client_id: "victual-label-worker" });
  record("S3", "ADR-0057 q6: a token proves one service only", "an account with no client is refused; the renderer's token naming the worker's client is refused", `intruder ${st(r1)}; renderer as worker ${st(r2)}`, !r1.access_token && !r2.access_token);
  const r3 = await cc(saToken("victual-label-worker", { ns: "kcsa-other" }));
  record("S4", "ADR-0057 q6", "an account of the same name in another namespace is refused", st(r3), !r3.access_token);
  const r4 = await cc(saToken("victual-label-worker", { audience: "https://kubernetes.default.svc" }));
  const r5 = await cc(saToken("victual-label-worker", { audience: `${KC}/realms/other` }));
  record("S5", "ADR-0057 q6", "a token for another audience (the API server, another realm) is refused", `API-server audience ${st(r4)}; other realm ${st(r5)}`, !r4.access_token && !r5.access_token);
}
// S6, S7: replay and lifetime.
{
  const t = saToken("victual-label-worker");
  const a = await cc(t), b = await cc(t);
  record("S6", "observation: replay", "the same assertion presented twice", `first ${st(a)}; second ${st(b)}`, "obs");
  const long = saToken("victual-label-worker", { duration: "24h" });
  const r = await cc(long);
  record("S7", "observation: a long-lived service-account token", "a 24 h TokenRequest token", `${st(r)}; token lifetime ${claims(long).exp - claims(long).iat} s`, "obs");
}
// S8: disabling the client in Keycloak.
{
  const c = await admin("GET", `/clients/${ids.worker}`);
  await admin("PUT", `/clients/${ids.worker}`, { ...c, enabled: false });
  const r = await cc(saToken("victual-label-worker"));
  await admin("PUT", `/clients/${ids.worker}`, { ...c, enabled: true });
  const back = await cc(saToken("victual-label-worker"));
  record("S8", "ADR-0057 d7: revocation", "a disabled client is refused; re-enabled, it works again", `disabled ${st(r)}; re-enabled ${st(back)}`, !r.access_token && !!back.access_token);
}
// S9, S10: deleting the account or the pod in Kubernetes, with tokens issued before.
{
  const saved = saToken("victual-label-renderer");
  kubectl("-n", NS, "delete", "sa", "victual-label-renderer");
  const r = await cc(saved);
  kubectl("-n", NS, "create", "sa", "victual-label-renderer");
  record("S9", "observation: an account deleted in Kubernetes", "a token issued before the deletion", `${st(r)}; Keycloak validates the signature offline and cannot see the deletion`, "obs");
  kubectl("-n", NS, "delete", "pod", "worker", "--wait=true");
  const p = await cc(podToken);
  record("S10", "observation: a pod deleted in Kubernetes", "the deleted pod's projected token", `${st(p)}; ${Math.round(claims(podToken).exp - Date.now() / 1000)} s left on it`, "obs");
}
// S11: no secret exists to use instead.
{
  const r = await token({ grant_type: "client_credentials", client_id: "victual-label-worker", client_secret: "anything" });
  record("S11", "ADR-0057 q6: no shared secret", "a client secret is refused for a federated-jwt client", st(r), !r.access_token);
}
// S12: the MCP sidecar's token exchange, authenticated by its service-account token.
{
  const u = await token({ grant_type: "password", client_id: "spike-user-client", username: "alice", password: ALICE_PASSWORD, scope: "openid" });
  const x = await token({ grant_type: TX, client_assertion_type: ASSERTION, client_assertion: saToken("victual-mcp"),
    subject_token: u.access_token, subject_token_type: "urn:ietf:params:oauth:token-type:access_token", audience: "victual-api" });
  const c = x.access_token ? claims(x.access_token) : {};
  record("S12", "ADR-0055 d7 with ADR-0057 q6: the sidecar exchanges with no stored secret", "exchange authenticated by the sidecar's service-account token; aud victual-api, azp victual-mcp, same sub",
    `user token ${st(u)}; exchange ${st(x)}; aud ${[].concat(c.aud ?? []).join(",")}; same sub: ${c.sub === (u.access_token && claims(u.access_token).sub)}`,
    [].concat(c.aud ?? []).includes("victual-api") && c.azp === "victual-mcp" && c.sub === claims(u.access_token).sub);
}

writeFileSync(new URL("./results.json", import.meta.url), JSON.stringify({ when: new Date().toISOString(), results }, null, 2));
console.log("| ID | Clause | Expected | Observed | Verdict |\n|---|---|---|---|---|");
for (const r of results) console.log(`| ${r.id} | ${r.clause} | ${r.expected} | ${r.observed.replaceAll("|", "/")} | ${r.verdict} |`);
process.exit(0);
