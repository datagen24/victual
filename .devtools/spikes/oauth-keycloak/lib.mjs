// Shared helpers for setup.mjs and probe.mjs: Keycloak admin REST, scripted browser login
// (authorization code + PKCE driven with fetch and a cookie jar), token calls and the
// resource-server check. node:crypto only, no npm dependencies.
import { createHash, createPublicKey, randomBytes, verify } from "node:crypto";
import { readFileSync } from "node:fs";

export const KC = process.env.KC_URL ?? "http://localhost:8180";
export const REALM = "victual";
export const ISSUER = `${KC}/realms/${REALM}`;
export const OIDC = `${ISSUER}/protocol/openid-connect`;
export const TOKEN = `${OIDC}/token`;
export const TX = "urn:ietf:params:oauth:grant-type:token-exchange";
export const AT = "urn:ietf:params:oauth:token-type:access_token";
export const ADMIN_USER = "admin";
// Generated by run.sh into .secrets.env (gitignored), so no credential is committed.
export const ADMIN_PASSWORD = /^ADMIN_PASS=(.*)$/m.exec(readFileSync(new URL("./.secrets.env", import.meta.url), "utf8"))[1];
export const REDIRECT = "http://127.0.0.1:8765/callback"; // never listened on: the code is read from the 302
export const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
export const claims = (t) => JSON.parse(Buffer.from(t.split(".")[1], "base64url"));
export const b64 = (b) => Buffer.from(b).toString("base64url");

// --- admin REST (bootstrap admin from the master realm)
let adminTok = { t: null, exp: 0 };
async function adminToken() {
  if (adminTok.exp > Date.now() + 5000) return adminTok.t;
  const r = await fetch(`${KC}/realms/master/protocol/openid-connect/token`, {
    method: "POST",
    body: new URLSearchParams({ grant_type: "password", client_id: "admin-cli", username: ADMIN_USER, password: ADMIN_PASSWORD }),
  });
  const j = await r.json();
  if (!j.access_token) throw new Error(`admin login failed: ${JSON.stringify(j)}`);
  adminTok = { t: j.access_token, exp: Date.now() + j.expires_in * 1000 };
  return adminTok.t;
}
export async function admin(method, path, body, { realm = REALM, raw = false } = {}) {
  // realm "" addresses /admin/realms itself; a path starting with /admin is used as given.
  const url = path.startsWith("/admin") ? `${KC}${path}` : `${KC}/admin/realms${realm ? `/${realm}` : ""}${path}`;
  const r = await fetch(url, {
    method,
    headers: { Authorization: `Bearer ${await adminToken()}`, "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  if (raw) return r;
  if (!r.ok) throw new Error(`${method} ${path} -> ${r.status} ${(await r.text()).slice(0, 400)}`);
  const text = await r.text();
  return text ? JSON.parse(text) : null;
}

// --- token endpoint
export async function token(body, headers = {}, url = TOKEN) {
  const r = await fetch(url, { method: "POST", headers, body: body instanceof URLSearchParams ? body : new URLSearchParams(body) });
  const text = await r.text();
  let j;
  try { j = JSON.parse(text); } catch { j = { raw: text.slice(0, 200) }; }
  return { status: r.status, ...j };
}
export const err = (r) => (r.error ? `${r.status} ${r.error}` : `${r.status} token`);
export const errd = (r) => `${err(r)}${r.error_description ? ` (${String(r.error_description).slice(0, 90)})` : ""}`;

export function exchange(by, subject, extra = {}) {
  const body = new URLSearchParams({ grant_type: TX, client_id: by.clientId, client_secret: by.secret, subject_token: subject, subject_token_type: AT });
  for (const [k, v] of Object.entries(extra)) for (const x of [].concat(v)) body.append(k, x);
  return token(body);
}

// --- scripted browser login: authorization code + PKCE (S256) against the realm's login form.
// `params` are extra authorization-request parameters (for example resource). Returns the
// code-exchange response, or { status, error, step } when the flow stops earlier.
function jarFetch() {
  const jar = new Map();
  return async (url, opts = {}) => {
    const headers = { ...(opts.headers ?? {}), Cookie: [...jar].map(([k, v]) => `${k}=${v}`).join("; ") };
    const r = await fetch(url, { ...opts, headers, redirect: "manual" });
    for (const c of r.headers.getSetCookie()) {
      const [kv] = c.split(";");
      const i = kv.indexOf("=");
      const name = kv.slice(0, i), value = kv.slice(i + 1);
      if (value === "" || /Max-Age=0/i.test(c)) jar.delete(name); else jar.set(name, value);
    }
    return r;
  };
}
const unescapeHtml = (s) => s.replaceAll("&amp;", "&").replaceAll("&#61;", "=").replaceAll("&quot;", '"');

// `f` reuses a cookie jar from an earlier login (login() returns it as `_f`): the second client then
// signs in through the first one's SSO session instead of getting a session of its own.
export async function authorize(client, { scope = "openid", params = {}, hint, verifier = b64(randomBytes(32)), f: shared } = {}) {
  const f = shared ?? jarFetch();
  const state = b64(randomBytes(8)), nonce = b64(randomBytes(8));
  const q = new URLSearchParams({
    client_id: client.clientId, response_type: "code", redirect_uri: client.redirect ?? REDIRECT, scope, state, nonce,
    code_challenge: b64(createHash("sha256").update(verifier).digest()), code_challenge_method: "S256",
  });
  for (const [k, v] of Object.entries(params)) { if (v === null) q.delete(k); else q.set(k, v); } // null removes a default
  if (hint) q.set("kc_idp_hint", hint);
  const r = await f(`${OIDC}/auth?${q}`);
  return { f, state, nonce, verifier, response: r, redirect: client.redirect ?? REDIRECT, client };
}
export async function submitLogin(a, user) {
  const html = await a.response.text();
  const m = html.match(/<form[^>]*id="kc-form-login"[^>]*action="([^"]+)"/) ?? html.match(/<form[^>]*action="([^"]+)"[^>]*id="kc-form-login"/);
  if (!m) return { status: a.response.status, error: "no_login_form", step: html.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").slice(0, 160) };
  const r = await a.f(unescapeHtml(m[1]), {
    method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams({ username: user.username, password: user.password, credentialId: "" }),
  });
  return { response: r };
}
export async function finishCode(a, r) {
  // Follow redirects by hand until the redirect_uri; the code is in its query string.
  for (let i = 0; i < 10; i++) {
    const loc = r.headers.get("location");
    if (!loc) {
      const text = await r.text();
      // A consent screen (client with Consent required): accept it and keep following.
      const form = text.match(/<form[^>]*action="([^"]+)"[^>]*>(?:(?!<\/form>)[\s\S])*name="accept"/);
      const code = text.match(/name="code"[^>]*value="([^"]*)"/) ?? text.match(/value="([^"]*)"[^>]*name="code"/);
      if (form && code && !a.consentScreen) {
        a.consentScreen = true;
        r = await a.f(new URL(unescapeHtml(form[1]), KC).toString(), { method: "POST", headers: { "Content-Type": "application/x-www-form-urlencoded" }, body: new URLSearchParams({ code: unescapeHtml(code[1]), accept: "Yes" }) });
        continue;
      }
      return { status: r.status, error: "no_redirect", step: text.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").slice(0, 200) };
    }
    const u = new URL(loc, KC);
    if (loc.startsWith(a.redirect)) {
      const err = u.searchParams.get("error");
      if (err) return { status: 400, error: err, error_description: u.searchParams.get("error_description") ?? "" };
      if (u.searchParams.get("state") !== a.state) return { status: 400, error: "state_mismatch" };
      return { code: u.searchParams.get("code"), iss: u.searchParams.get("iss") };
    }
    r = await a.f(u.toString());
  }
  return { status: 0, error: "too_many_redirects" };
}
// Full interactive-style login: returns the token response (with refresh_token, id_token).
export async function login(client, user, opts = {}) {
  const a = await authorize(client, opts);
  let fin;
  if (a.response.status >= 300 && a.response.status < 400) {
    // A redirect is either an error for the redirect_uri or (kc_idp_hint) a hop to an upstream IdP.
    fin = await finishCode(a, a.response);
  } else if (a.response.status >= 400) {
    const t = await a.response.text();
    return { status: a.response.status, error: "authorize_refused", error_description: t.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim().slice(0, 160) };
  } else {
    const s = await submitLogin(a, user);
    if (!s.response) return s;
    fin = await finishCode(a, s.response);
  }
  if (!fin.code) return { status: fin.status ?? 400, ...fin };
  const body = { grant_type: "authorization_code", client_id: client.clientId, code: fin.code, redirect_uri: a.redirect, code_verifier: a.verifier };
  if (client.secret) body.client_secret = client.secret;
  const t = await token(body);
  return { ...t, _code: fin.code, _iss: fin.iss, _verifier: a.verifier, _redirect: a.redirect, _f: a.f };
}

// --- resource-server check (ADR-0055 decision 3): RS256 against the JWKS from the discovery
// document, discovery issuer equals the pinned issuer, iss, exp/nbf with 60 s skew, aud must
// contain the configured audience, empty aud refused. No Keycloak-specific code.
const jwksCache = new Map();
export async function rsCheck(tok, { issuer, discovery, audience }) {
  try {
    const meta = await (await fetch(discovery)).json();
    if (meta.issuer !== issuer) return `discovery issuer ${meta.issuer} != pinned ${issuer}`;
    if (!jwksCache.has(meta.jwks_uri)) jwksCache.set(meta.jwks_uri, (await (await fetch(meta.jwks_uri)).json()).keys);
    const [h, p, sig] = tok.split(".");
    const head = JSON.parse(Buffer.from(h, "base64url"));
    const jwk = jwksCache.get(meta.jwks_uri).find((k) => k.kid === head.kid);
    if (!jwk || head.alg !== "RS256") return `no RS256 key for kid ${head.kid} (alg ${head.alg})`;
    if (!verify("RSA-SHA256", Buffer.from(`${h}.${p}`), createPublicKey({ key: jwk, format: "jwk" }), Buffer.from(sig, "base64url"))) return "bad signature";
    const c = claims(tok), now = Date.now() / 1000;
    if (c.iss !== issuer) return `iss ${c.iss}`;
    if (!(c.exp + 60 > now)) return "expired";
    if (c.nbf && c.nbf - 60 > now) return "not yet valid";
    const aud = [].concat(c.aud ?? []);
    if (!aud.length) return "empty aud";
    if (!aud.includes(audience)) return `aud ${aud.join(",")} lacks ${audience}`;
    return "accepted";
  } catch (e) { return `error ${e.message}`; }
}
