	$db->exec('DELETE FROM user_permissions_resolved');
	$denied = $controller->Resolve($request, new Slim\Psr7\Response(), ['code' => $apiUid]);
	$unknown = $controller->Resolve($request, new Slim\Psr7\Response(), ['code' => '0000000000000']);
