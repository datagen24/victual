	$db->exec("CREATE TABLE user_permissions_resolved (id INTEGER, user_id INTEGER, permission_name TEXT);
		INSERT INTO user_permissions_resolved VALUES (1, 1, 'STOCK_VIEW');
		ALTER TABLE locations ADD COLUMN description TEXT;
		ALTER TABLE locations ADD COLUMN row_created_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
		ALTER TABLE locations ADD COLUMN is_freezer SMALLINT DEFAULT 0;
		ALTER TABLE locations ADD COLUMN parent_location_id INTEGER;
		CREATE TABLE userfields (id INTEGER, entity TEXT, sort_number INTEGER, name TEXT);
		CREATE TABLE userentities (id INTEGER, name TEXT);
		CREATE COLLATION nocase (provider = libc, locale = 'C');
		CREATE TABLE userfield_values (id INTEGER, field_id INTEGER, object_id INTEGER, value TEXT);
		CREATE TABLE userfield_values_resolved (id INTEGER, entity TEXT, object_id INTEGER, name TEXT, value TEXT);
		INSERT INTO locations (id, name) VALUES (1, 'API shelf')");
	$container = new DI\Container(); $container->set('view', null);
	$controller = new Victual\Controllers\Api\LabelsApiController($container);
	$request = (new Slim\Psr7\Factory\ServerRequestFactory())->createServerRequest('GET', '/');
