/**
 * The highest migration number on disk.
 *
 * Hard-coded here until plan 27 added 0271, at which point this fixture started failing for
 * a reason that had nothing to do with what it tests: DatabaseImporter compares what the
 * target recorded against what the code ships, so a fixture claiming an older number is
 * refused before the guard under test ever runs.
 */
function LatestMigrationNumber(): int
{
	$highest = 0;
	foreach (glob(VICTUAL_ROOT_PATH . '/migrations/*') as $file)
	{
		// DOALWAYS_MIGRATION_ID (8888) runs on every boot and is not part of the sequence
		// GetLatestMigrationNumber() reports, so it is excluded here for the same reason.
		if (preg_match('/^(\\d{4})\\./', basename($file), $matches)
			&& (int)$matches[1] !== \Victual\Services\DatabaseMigrationService::DOALWAYS_MIGRATION_ID)
		{
			$highest = max($highest, (int)$matches[1]);
		}
	}
	return $highest;
}

function Connect(string $schema): PDO
{
	$db = new PDO(getenv('LABEL_TEST_DSN'), getenv('PGUSER'), getenv('PGPASSWORD'), [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
	$db->exec('SET search_path TO ' . $schema);
	$db->exec("SET statement_timeout = '8s'");
	return $db;
}

function Import(PDO $db, ?callable $progress = null, bool $force = true): void
{
	$source = new PDO('sqlite::memory:');
	$source->exec("CREATE TABLE migrations (migration INTEGER); INSERT INTO migrations VALUES (265);
		CREATE TABLE locations (id INTEGER, name TEXT); INSERT INTO locations VALUES (1, 'Replacement')");
	(new DatabaseImporter($source, $db, new PostgresDialect(), $progress))->Import($force, false);
}

