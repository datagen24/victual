	if ($db->inTransaction()) { $db->rollBack(); }
	$db->exec('DROP SCHEMA ' . $schema . ' CASCADE');
	if (is_dir($cachePath))
	{
		$entries = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($cachePath, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST);
		foreach ($entries as $entry)
		{
			$entry->isDir() ? rmdir($entry->getPathname()) : unlink($entry->getPathname());
		}
		rmdir($cachePath);
	}
}
