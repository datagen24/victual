 if($artifact===null)throw new RuntimeException('No render request was pending');
 tx($db,fn()=>(new LabelOperationsService($db))->AttachArtifact((int)$artifact['render_request_id'],(int)$artifact['id']));
 return $artifact;
}

/** Paints the resolved render input as a conforming raster/png-indexed;v=1 artifact. */
function paintArtifact(array $input,?callable $mutate=null): string
{
 $profile=$input['profile'];$document=$input['document'];
 $width=(int)$profile['raster_width_px'];
 $dpiX=(int)$profile['dpi_x'];$dpiY=(int)$profile['dpi_y'];
 $heightMm=$document['canvas']['height_mm']??$document['canvas']['max_height_mm'];
 $height=(int)round($heightMm*$dpiY/25.4);
 $palette=$profile['pixel_policy']['palette'];
 $white=array_search('#ffffff',$palette,true);$black=array_search('#000000',$palette,true);
 $pixels=array_fill(0,$height,array_fill(0,$width,$white));
 foreach($document['elements'] as $element)
 {
  if($element['type']!=='qr')continue;
  $matrix=$input['qr'][$element['id']];
  $mx=(int)round($element['module_mm']*$dpiX/25.4);$my=(int)round($element['module_mm']*$dpiY/25.4);
  $ox=(int)round($element['x_mm']*$dpiX/25.4)+$element['quiet_zone_modules']*$mx;
  $oy=(int)round($element['y_mm']*$dpiY/25.4)+$element['quiet_zone_modules']*$my;
  for($r=0;$r<$matrix['size'];$r++)for($c=0;$c<$matrix['size'];$c++)
  {
   if($matrix['modules'][$r][$c]!=='1')continue;
   for($dy=0;$dy<$my;$dy++)for($dx=0;$dx<$mx;$dx++)
   {
    $y=$oy+$r*$my+$dy;$x=$ox+$c*$mx+$dx;
    if($y<$height&&$x<$width)$pixels[$y][$x]=$black;
   }
  }
 }
 if($mutate!==null)$mutate($pixels,$width,$height);
 return encodeIndexedPng($pixels,$width,$height,$palette);
}

/** A minimal colour-type-3, bit-depth-2 PNG encoder. */
function encodeIndexedPng(array $pixels,int $width,int $height,array $palette): string
{
 $chunk=function(string $type,string $data){return pack('N',strlen($data)).$type.$data.pack('N',crc32($type.$data));};
 $ihdr=pack('NN',$width,$height).chr(2).chr(3).chr(0).chr(0).chr(0);
 $plte='';foreach($palette as $colour)$plte.=hex2bin(substr($colour,1));
 $raw='';
 foreach($pixels as $row)
 {
  $line='';$acc=0;$filled=0;
  foreach($row as $index)
  {
   $acc=($acc<<2)|($index&3);$filled++;
   if($filled===4){$line.=chr($acc);$acc=0;$filled=0;}
  }
  if($filled>0)$line.=chr($acc<<(2*(4-$filled)));
  $raw.=chr(0).$line;
 }
 return "\x89PNG\r\n\x1a\n".$chunk('IHDR',$ihdr).$chunk('PLTE',$plte).$chunk('IDAT',gzcompress($raw,9)).$chunk('IEND','');
}
