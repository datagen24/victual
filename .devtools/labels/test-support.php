/**
 * The renderer, as a fixture.
 *
 * It does exactly what the real one will: claim a durable request, read the resolved input,
 * paint the module matrix Victual computed at the geometry the profile fixes, and submit
 * indexed PNG bytes. Nothing here is a shortcut past verification - ArtifactService checks
 * these bytes the same way it will check the Rust renderer's.
 */
function renderPending(PDO $db,string $rendererId='fixture-renderer'): ?array
{
 $requests=new RenderRequestService($db);
 $input=tx($db,fn()=>$requests->Claim());
 if($input===null)return null;
 $bytes=paintArtifact($input);
 return tx($db,fn()=>(new ArtifactService($db))->Accept($input['render_request_id'],$input['generation_token'],$bytes,$rendererId,'0.0.1-fixture'));
}

/** Renders whatever is pending and attaches it to the job that was waiting for it. */
function renderAndAttach(PDO $db,int $jobId): array
{
